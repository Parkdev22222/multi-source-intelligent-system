"""
Merge report-eval passes that could not share a GPU into one table.

EXAONE-4.0-32B is 60 GB of weights and Qwen2.5-VL-7B another 16.6 GB: on one
80 GB card they cannot be resident together, so the text conditions and the
image-conditioned baseline have to run as two invocations. `run_report_eval`
writes `results` from the modes of *that* invocation and overwrites the JSON,
so the second pass does not extend the first -- it replaces it. Before this
module the merge was done by hand, and a hand-merged table cannot say which
pairing head produced which row. `results/pilot_cc_scenes8` is exactly that:
its rows were generated by the 60-tile pilot head, and nothing in the file
recorded it.

What this does instead: take rows from a donor run, check that the two runs
actually describe the same measurement, stamp each row with where it came
from, and re-emit the LaTeX through the same code path `run_report_eval` uses.

    python -m icce.eval.merge_passes \\
        --into results/e4_scenes8_head445 \\
        --from results/pilot_cc_scenes8 \\
        --modes vlm_direct

Rows are ordered by `GROUNDING_MODES`, so the grounding ladder reads in the
order the paper argues it, whichever invocation produced each row.
"""

from __future__ import annotations

import argparse
import json
import logging
import sys
from pathlib import Path
from typing import Dict, List, Optional, Sequence

from icce.report.prompts import GROUNDING_MODES

logger = logging.getLogger(__name__)

# Fields that must agree for two passes to describe the same measurement. A
# donor row scored over different crops, a different split or a different
# number of pairs is not the same experiment, and silently pasting it into the
# table would be the most expensive kind of quiet error.
MUST_MATCH = ("dataset", "split", "style", "n_pairs")

# Fields recorded per merged row so the JSON says what produced it.
PROVENANCE = ("checkpoint", "llm", "vlm", "cache", "n_pairs")


def _load(run_dir: Path, style: str) -> Dict:
    path = run_dir / f"report_results_{style}.json"
    if not path.is_file():
        raise SystemExit(f"no {path.name} in {run_dir}")
    return json.loads(path.read_text(encoding="utf-8"))


def _rows(payload: Dict) -> Dict[str, Dict]:
    return {r["name"]: r for r in payload.get("results", [])}


def check_compatible(into: Dict, donor: Dict) -> tuple:
    """Compare the two passes field by field.

    Returns (disagreements, unverifiable). A field carried by both runs and
    holding different values is a disagreement and blocks the merge. A field
    one run records and the other does not says nothing either way -- the
    writer changed, not the experiment -- so it is reported rather than
    treated as agreement. `check_same_pairs` is the check that does not
    depend on either run's metadata.
    """
    bad, unknown = [], []
    for key in MUST_MATCH:
        a, b = into.get(key), donor.get(key)
        if a is None or b is None:
            if a is not None or b is not None:
                unknown.append(f"{key}: {a!r} vs {b!r}")
            continue
        if a != b:
            bad.append(f"{key}: {a!r} vs {b!r}")
    return bad, unknown


def check_same_pairs(into_dir: Path, donor_dir: Path, mode: str,
                     style: str) -> Optional[str]:
    """Compare the generated pair ids of a donor mode against this run's.

    The metadata check above compares counts; this compares identity. Two runs
    over 128 crops each are not the same 128 crops.
    """
    donor_gen = donor_dir / f"gen_{mode}_{style}.jsonl"
    if not donor_gen.is_file():
        return f"{mode}: donor has no {donor_gen.name}"

    ours = sorted(into_dir.glob(f"gen_*_{style}.jsonl"))
    ours = [p for p in ours if p.name != donor_gen.name]
    if not ours:
        return None  # nothing local to compare against; metadata check stands

    def keys(path: Path) -> set:
        return {json.loads(line)["key"] for line in
                path.read_text(encoding="utf-8").splitlines() if line.strip()}

    donor_keys, local_keys = keys(donor_gen), keys(ours[0])
    if donor_keys != local_keys:
        only_donor = len(donor_keys - local_keys)
        only_local = len(local_keys - donor_keys)
        return (f"{mode}: pair ids differ from {ours[0].name} "
                f"({only_donor} only in donor, {only_local} only here)")
    return None


def merge(into_dir: Path, donor_dir: Path, modes: Sequence[str],
          style: str = "caption", out_dir: Optional[Path] = None,
          force: bool = False) -> Dict:
    into = _load(into_dir, style)
    donor = _load(donor_dir, style)

    bad, unknown = check_compatible(into, donor)
    if bad:
        msg = "; ".join(bad)
        if not force:
            raise SystemExit(
                f"refusing to merge: the two passes disagree on {msg}.\n"
                "They do not describe the same measurement. Re-run the donor "
                "modes against the same cache, or pass --force if you have "
                "checked this by hand and can defend it in the paper.")
        logger.warning("merging despite disagreement on %s (--force)", msg)
    for field in unknown:
        logger.warning("only one pass records %s -- compared by pair id instead",
                       field)

    into_rows, donor_rows = _rows(into), _rows(donor)
    merged = dict(into_rows)
    notes: List[str] = []

    for mode in modes:
        if mode not in donor_rows:
            raise SystemExit(f"donor {donor_dir} has no row for {mode!r} "
                             f"(has: {', '.join(donor_rows) or 'nothing'})")
        problem = check_same_pairs(into_dir, donor_dir, mode, style)
        if problem:
            if not force:
                raise SystemExit(f"refusing to merge: {problem}")
            logger.warning("merging despite: %s (--force)", problem)

        row = dict(donor_rows[mode])
        row["_merged_from"] = {
            "run": str(donor_dir),
            **{k: donor.get(k) for k in PROVENANCE if donor.get(k) is not None},
        }
        if mode in into_rows:
            logger.warning("%s already present in %s; the donor row replaces it",
                           mode, into_dir)
        merged[mode] = row
        notes.append(f"{mode} from {donor_dir}")

    # The ladder is an argument, not a list: keep the canonical order so the
    # table reads the way the paper reasons about it, then anything unexpected.
    ordered = [merged[m] for m in GROUNDING_MODES if m in merged]
    ordered += [r for name, r in merged.items() if name not in GROUNDING_MODES]

    payload = dict(into)
    payload["results"] = ordered
    payload["merged"] = notes
    if unknown:
        payload["merged_unverified_fields"] = unknown
    for row in ordered:
        row.setdefault("_merged_from", {"run": str(into_dir),
                                        **{k: into.get(k) for k in PROVENANCE
                                           if into.get(k) is not None}})

    out = Path(out_dir or into_dir)
    _emit(payload, out, style)
    return payload


def _emit(payload: Dict, out: Path, style: str) -> None:
    """Write JSON and LaTeX through the same helpers run_report_eval uses."""
    from icce.eval.tables import (latex_table, print_console_table, save_json,
                                  save_latex)

    rows = payload["results"]
    save_json(payload, out / f"report_results_{style}.json")

    if style == "caption":
        cols = ["BLEU-1", "BLEU-4", "METEOR", "ROUGE-L", "CIDEr-D"]
        print_console_table("LEVIR-CC caption metrics", cols, rows)
        save_latex(latex_table(
            "Captioning performance on LEVIR-CC.",
            "tab:levir_cc_caption", cols, rows, baseline_group="levir_cc",
            mono_rows=True,
        ), out / "table_levir_cc_caption.tex")

    fact_cols = ["cfs_precision", "cfs_recall", "cfs_f1",
                 "hallucination_rate", "change_accuracy"]
    print_console_table(f"Report factuality ({style})", fact_cols, rows)
    save_latex(latex_table(
        f"Report factuality by grounding condition ({style} style). "
        "CFS is claim-level precision/recall against the human references; "
        "Hal is the share of generated claims with no ground-truth support.",
        f"tab:factuality_{style}",
        ["CFS-P", "CFS-R", "CFS-F1", "Hal", "ChgAcc"], rows,
        metric_map={"CFS-P": "cfs_precision", "CFS-R": "cfs_recall",
                    "CFS-F1": "cfs_f1", "Hal": "hallucination_rate",
                    "ChgAcc": "change_accuracy"},
        mono_rows=True,
    ), out / f"table_factuality_{style}.tex")


def main(argv: Optional[Sequence[str]] = None) -> int:
    logging.basicConfig(level=logging.INFO, format="%(asctime)s %(levelname)s %(message)s")
    ap = argparse.ArgumentParser(description=__doc__,
                                 formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--into", required=True, type=Path,
                    help="run whose rows are kept; receives the merged table")
    ap.add_argument("--from", dest="donor", required=True, type=Path,
                    help="run to take the missing rows from")
    ap.add_argument("--modes", nargs="+", required=True,
                    help="modes to take from the donor, e.g. vlm_direct")
    ap.add_argument("--style", default="caption", choices=("caption", "report"))
    ap.add_argument("--out", type=Path, default=None,
                    help="write here instead of overwriting --into")
    ap.add_argument("--force", action="store_true",
                    help="merge even when the passes disagree; the "
                         "disagreement is logged and kept in the JSON")
    args = ap.parse_args(argv)

    payload = merge(args.into, args.donor, args.modes, style=args.style,
                    out_dir=args.out, force=args.force)
    logger.info("merged %d rows: %s", len(payload["results"]),
                ", ".join(r["name"] for r in payload["results"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
